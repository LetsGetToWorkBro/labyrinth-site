#!/usr/bin/env python3
"""Download the photos in a shared Adobe Lightroom album.

    python3 scripts/lightroom-album.py <share-url> <out-dir> [--size 2048]

A share link (https://lightroom.adobe.com/shares/<id>) is a web app, but the page
carries the ids it needs and the photos themselves come from a public API that
needs no sign-in, so there is nothing to export by hand.

    1. The page names the album: .../spaces/<space>/albums/<album>/assets
    2. The API lists the album's assets, each with links to renditions of several
       sizes (640, 1280, 2048, ...). The API answers with "while (1) {}" in front of
       the JSON, which is stripped here.
    3. The largest rendition at or under --size is downloaded to <out-dir>, named
       <position>-<original file name>, and album.json records what each photo is.

Nothing is written to the album. The sizes on offer are whatever the photographer
exported: the October 2026 shoot was exported at 2048 px on the long edge, so that
is the most there is; a Lightroom "fullsize" rendition has to be generated by the
owner's own login and is not attempted here.
"""
import argparse, json, os, re, subprocess, sys

API_KEY = "LightroomMobileWeb1"   # the key the share page itself uses


def fetch(url, out=None):
    cmd = ["curl", "-sS", "-L", "--max-time", "90", "-H", "X-API-Key: " + API_KEY]
    if out:
        cmd += ["-o", out]
    return subprocess.check_output(cmd + [url])


def api_json(url):
    raw = fetch(url).decode("utf-8", "replace")
    return json.loads(re.sub(r"^\s*while\s*\(1\)\s*\{\}\s*", "", raw))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("url")
    ap.add_argument("out")
    ap.add_argument("--size", type=int, default=2048, help="largest rendition to take (default 2048)")
    ap.add_argument("--list", action="store_true", help="only list the photos, download nothing")
    a = ap.parse_args()

    page = fetch(a.url).decode("utf-8", "replace")
    m = re.search(r"spaces/([0-9a-f]{32})/albums/([0-9a-f]{32})/assets", page)
    if not m:
        sys.exit("this does not look like a Lightroom share page (no album found)")
    space, album = m.groups()
    title = (re.search(r"<title>(.*?)</title>", page, re.S) or [None, ""])[1].strip()
    base = "https://photos.adobe.io/v2/"
    url = "%sspaces/%s/albums/%s/assets?embed=asset&subtype=image%%3Bvideo&limit=500&api_key=%s" % (base, space, album, API_KEY)

    resources = []
    while url:
        j = api_json(url)
        resources += j["resources"]
        nxt = ((j.get("links") or {}).get("next") or {}).get("href")
        url = (j["base"] + nxt + ("&" if "?" in nxt else "?") + "api_key=" + API_KEY) if nxt else None

    rows = []
    for i, r in enumerate(resources):
        asset = r["asset"]
        pay = asset["payload"]
        imp = pay.get("importSource", {})
        sizes = sorted(int(k.rsplit("/", 1)[1]) for k in asset["links"] if re.search(r"/rels/rendition_type/\d+$", k))
        pick = max([s for s in sizes if s <= a.size] or sizes[:1] or [0])
        href = asset["links"].get("/rels/rendition_type/%d" % pick, {}).get("href")
        name = imp.get("fileName") or asset["id"]
        rows.append({
            "position": i, "id": asset["id"], "file": "%02d-%s" % (i, name), "type": asset["subtype"],
            "width": imp.get("originalWidth"), "height": imp.get("originalHeight"),
            "captured": pay.get("captureDate"), "rendition": pick,
            "url": (r.get("base") or j["base"]) + href if href else None,
        })
    print("%s: %d photos" % (title or "album", len(rows)))
    if a.list:
        for r in rows:
            print("  %2d  %-28s %sx%s  %s" % (r["position"], r["file"], r["width"], r["height"], (r["captured"] or "")[:19]))
        return
    os.makedirs(a.out, exist_ok=True)
    for r in rows:
        if not r["url"]:
            print("  skipped %s (no rendition)" % r["file"]); continue
        dest = os.path.join(a.out, os.path.splitext(r["file"])[0] + ".jpg")
        fetch(r["url"] + "?api_key=" + API_KEY, dest)
    json.dump({"title": title, "space": space, "album": album, "photos": [{k: v for k, v in r.items() if k != "url"} for r in rows]},
              open(os.path.join(a.out, "album.json"), "w"), indent=1)
    print("wrote %d photos and album.json to %s" % (len(rows), a.out))


if __name__ == "__main__":
    main()
